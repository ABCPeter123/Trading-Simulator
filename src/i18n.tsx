const LocaleContext = createContext<{
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (english: string) => string;
} | null>(null);

export function translate(english: string, locale: Locale): string {
  if (locale === "en") return english;
  return zh[english] ?? english;
}

function initialLocale(): Locale {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "zh-CN") return stored;
  } catch { /* Browser storage may be unavailable. */ }
  return "en";
}

export function I18nProvider({children}: {children: ReactNode}) {
  const [locale, changeLocale] = useState<Locale>(initialLocale);
  const setLocale = useCallback((next: Locale) => {
    changeLocale(next);
    try { localStorage.setItem(STORAGE_KEY, next); } catch { /* ignore */ }
  }, []);
  useEffect(() => {
    document.documentElement.lang = locale;
    document.title = locale === "zh-CN" ? "交易模拟器 · Trading Simulator" : "Trading Simulator";
  }, [locale]);
  const value = useMemo(() => ({
    locale, setLocale,
    t: (english: string) => translate(english, locale),
  }), [locale, setLocale]);
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useI18n() {
  const context = useContext(LocaleContext);
  if (!context) throw new Error("I18nProvider is missing.");
  return context;
}

export function LanguageSwitcher() {
  const {locale, setLocale} = useI18n();
  return <div className="ts-lang-switch" role="group" aria-label="Language / 语言">
    <Languages size={15} aria-hidden="true"/>
    <button type="button" aria-pressed={locale === "en"} className={locale === "en"?"active":""}
      onClick={()=>setLocale("en")}>EN</button>
    <button type="button" aria-pressed={locale === "zh-CN"} className={locale === "zh-CN"?"active":""}
      onClick={()=>setLocale("zh-CN")}>中文</button>
  </div>;
}
